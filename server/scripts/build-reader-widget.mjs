import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "../..");
const htmlPath = resolve(repoRoot, "web/dist/index.html");
const generatedPath = resolve(repoRoot, "server/src/mcp/reader-widget.generated.ts");
const pnpmEntrypoint = process.env.npm_execpath;

function runPnpm(args) {
  execFileSync(
    pnpmEntrypoint ? process.execPath : "pnpm",
    pnpmEntrypoint ? [pnpmEntrypoint, ...args] : args,
    { cwd: repoRoot, stdio: "inherit" }
  );
}

runPnpm(["--filter", "@ss/shared", "build"]);
runPnpm(["--filter", "@ss/web", "build"]);

const html = readFileSync(htmlPath, "utf8");
const generated = [
  "// Generated by server/scripts/build-reader-widget.mjs. Do not edit by hand.",
  `export const READER_WIDGET_HTML = ${JSON.stringify(html)};`,
  ""
].join("\n");

try {
  if (readFileSync(generatedPath, "utf8") === generated) process.exit(0);
} catch {
  // The first build creates the generated module.
}

writeFileSync(generatedPath, generated);
